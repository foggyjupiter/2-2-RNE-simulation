h2("Ⅱ. 이론적 배경 — 2. 인공지능 관련 이론적 배경")
note("※ 스펙트로그램·멜 척도·CNN의 기초는 1차 연구 보고서 2장과 같아 생략하고, 본 연구에서 새로 쓴 기법만 정리한다. 시뮬레이터(DEM·충돌음 합성)의 이론은 물리 파트 참고.")
h3("2.1 시뮬레이션 기반 학습과 시뮬레이션-실측 간극")
p("시뮬레이션은 정답(개수와 물성)이 정확히 달린 데이터를 원하는 만큼 만들 수 있지만, 시뮬레이션이 만드는 소리의 분포는 실제 녹음의 분포와 완전히 같지 않다. "
  "이 차이를 시뮬레이션-실측 간극(sim2real gap)이라 하며, 시뮬레이션에서 잘 맞는 모델도 이 차이가 큰 단서에 기대면 실측에서 크게 틀린다. "
  "Ben-David 등[3]은 실측(목표 영역) 오차가 시뮬레이션(원천 영역) 오차와 두 영역 분포 사이의 거리의 합으로 위에서 제한됨을 보였다. 즉 실측 성능을 높이려면 두 분포를 가깝게 만들거나, 모델이 두 분포에서 똑같이 보이는 단서만 쓰도록 해야 한다.")
eq("시뮬레이션-실측 오차 한계 (Ben-David 등)", "epsilon _{T} (h) LEQ epsilon _{S} (h) + {1} over {2} d _{H DELTA H} (S,T) + lambda ^{*}")
h3("2.2 도메인 무작위화")
p("도메인 무작위화[1]는 정확히 알 수 없는 조건(마이크 게인, 잔향, 잡음 크기, 충돌음 모양 등)을 학습 데이터에서 넓게 바꿔, 모델이 특정 합성 디테일에 기대지 못하게 하는 방법이다. "
  "실제 환경이 학습 데이터의 다양성 안에 들어오면 실측을 '또 하나의 변형'으로 처리할 수 있다. 다만 무작위화한 값이 현실과 다른 분포를 만들면 오히려 모델이 잘못된 단서를 배울 수 있으며, 본 연구는 그 실제 사례를 발견하였다(Ⅳ-2.2).")
h3("2.3 도메인 적대 학습(DANN)")
p("도메인 적대 학습[2]은 정답이 없는 실측 녹음을 학습에 함께 넣는다. 특징 추출기 뒤에 '이 소리가 시뮬레이션인가 실측인가'를 맞히는 판별기를 붙이고, 판별기는 맞히도록, 특징 추출기는 판별기를 속이도록 학습한다. "
  "이를 위해 특징 추출기와 판별기 사이에 기울기 반전층(gradient reversal layer)을 두어, 역전파할 때 판별기 손실의 기울기 부호를 뒤집는다. 그 결과 특징 공간에서 시뮬레이션 특유의 단서가 지워지고, 두 영역에서 모두 통하는 단서로 개수를 세게 된다. "
  "적대 손실의 무게 λ는 학습 초반 0에서 서서히 올린다.")
eq("DANN 목적 함수", "min _{theta _{f} , theta _{y}} max _{theta _{d}} `` L _{y} ( theta _{f} , theta _{y} ) - lambda L _{d} ( theta _{f} , theta _{d} )")
eq("적대 손실 무게 일정 (p: 학습 진행률 0→1)", "lambda (p) = lambda _{max} LEFT ( {2} over {1+e ^{-10p}} -1 RIGHT ) ,`` lambda _{max} =0.3")
h3("2.4 불확도를 함께 내는 회귀와 구간 보정")
p("물질을 모르면 같은 소리에 여러 개수가 대응할 수 있으므로, 모델은 개수의 추정값 μ와 함께 불확도 σ를 출력하도록 하였다(이분산 회귀[9,10]). "
  "가우시안 음의 로그우도를 손실로 쓰면, 모델은 헷갈리는 입력에서 σ를 크게 내어 '자신 없음'을 표시한다. 학습이 끝난 뒤에는 검증 데이터에서 σ의 크기를 다시 맞추고, "
  "분할 컨포멀 예측[11]으로 '90% 확률로 이 구간 안'이라는 구간을 만든다.")
eq("가우시안 음의 로그우도", "L _{NLL} = {1} over {2} LEFT [ log sigma ^{2} + {(y- mu ) ^{2}} over {sigma ^{2}} RIGHT ]")
eq("컨포멀 구간 (q: 검증 데이터의 |y-μ|/σ 분위수)", "hat{y} ± q CDOT hat{sigma}")
h3("2.5 개수 출력 방식")
p("개수는 순서가 있는 값이므로 출력 방식에 따라 학습이 달라질 수 있다. 회귀는 개수를 연속값으로 바로 예측하고, 분류는 0~100을 구간으로 나눠 확률을 낸다(1차 연구 방식). "
  "소프트 라벨 분류는 정답 주변 구간에도 확률을 나눠 주어 인접 오류를 덜 벌하며, CORAL[4]은 'N이 k보다 큰가'를 묻는 이진 분류 여러 개로 순서를 보존한다. 본 연구는 네 방식을 같은 조건에서 비교하였다.")
h3("2.6 여러 가진 조건을 종합하는 집합 모델")
p("같은 용기를 여러 가진 속도로 흔들면, 녹음 하나에서는 섞여 있던 개수와 물성의 효과가 조건마다 다르게 변한다. 이 녹음 묶음을 종합하려면 입력 순서에 무관하고 개수가 바뀌어도 작동하는 집합 모델이 필요하다[5,6]. "
  "본 연구는 각 녹음을 같은 인코더로 처리한 뒤 가진 세기 Γ를 임베딩해 더하고, 자기주의(self-attention)로 녹음들을 함께 보며, 이웃 조건 사이의 차이를 따로 모은다. "
  "또 묶음 전체의 공통 음량을 빼서, 마이크 게인이나 입자 질량처럼 모든 조건에 똑같이 곱해지는 요인을 구조적으로 지운다.")
eq("순서에 무관한 집합 함수 (Deep Sets)", "f(X) = rho LEFT ( sum _{x IN X} phi (x) RIGHT )")
h3("2.7 식별 가능성과 크라메르-라오 하한")
p("학습 이전에, 소리에 개수 정보가 얼마나 들어 있는지를 이론적으로 잴 수 있다. 관측 통계가 개수 N과 물성 θ에 의존할 때, 피셔 정보 행렬 I로 어떤 추정기도 넘을 수 없는 오차 하한(크라메르-라오 하한[7])을 얻는다. "
  "물성을 모르면 θ를 함께 추정해야 하므로 N에 대한 정보 일부가 θ와 겹쳐 사라지고, 하한이 커진다. 이 비율은 '물질을 모르면 원리적으로 얼마나 어려워지는가'를 보여 준다.")
eq("크라메르-라오 하한", "sigma _{N} GEQ sqrt {LEFT ( I ^{-1} RIGHT ) _{NN}}")
h3("2.8 선형 탐침")
p("학습된 모델이 무엇을 배웠는지 보기 위해, 모델의 내부 표현(마지막 은닉층 벡터)에서 어떤 물리량을 선형 회귀로 얼마나 복원할 수 있는지 잰다(선형 탐침[8]). "
  "복원 R²가 높으면 그 물리량이 모델 내부에 명시적으로 표현되어 있다는 뜻이다.")
