h3("2.7 평가 방법")
p("모든 실험은 같은 분할, 같은 지표로 평가하였다. 주 지표는 개수 평균 절대오차(MAE)와 편향이다.")
eq(r"\mathrm{MAE} = \frac{1}{n}\sum_{i=1}^{n} \left| \hat{N}_i - N_i \right|",
   "{rm MAE} = {1} over {n} sum _{i=1} ^{n} LEFT | hat{N} _{i} - N _{i} RIGHT |")
eq(r"\text{편향} = \frac{1}{n}\sum_{i=1}^{n} (\hat{N}_i - N_i)",
   "편향 = {1} over {n} sum _{i=1} ^{n} ( hat{N} _{i} - N _{i} )")
p("여기서 N_i는 i번째 녹음의 실제 개수, N̂_i는 예측 개수, n은 평가 녹음 수이다. MAE는 평균적으로 몇 개 틀리는지를, 편향은 개수를 많게(양수) 또는 적게(음수) 세는 경향을 나타낸다. "
  "이와 함께 오차 5개·10개 이내 비율, 90% 예측 구간의 실제 포함률, 물성 추정 R², 개수 오차와 지름 오차의 상관(혼동 진단), 개수 구간별 오차를 기록하였다.")
p("실측 녹음의 가진 속도는 녹음마다 6.04~6.64 Hz로 흔들렸으므로, 예측이 이 흔들림에 얼마나 휘둘리는지도 쟀다(속도 민감도). 개수 자체의 영향이 섞이지 않도록 같은 개수의 녹음끼리 평균을 뺀 뒤, 예측 오차를 녹음별 가진 주파수에 회귀한 기울기로 정의하였다.")
eq(r"S = \frac{\sum_i (f_i - \bar{f}_{N_i})(e_i - \bar{e}_{N_i})}{\sum_i (f_i - \bar{f}_{N_i})^2},\quad e_i = \hat{N}_i - N_i",
   "S = {sum _{i} ( f _{i} - bar{f} _{N _{i}} ) ( e _{i} - bar{e} _{N _{i}} )} over {sum _{i} ( f _{i} - bar{f} _{N _{i}} ) ^{2}} ,```` e _{i} = hat{N} _{i} - N _{i}")
p("여기서 f_i는 녹음에서 추정한 가진 주파수, 윗줄(f̄, ē)은 같은 개수 녹음들의 평균이다. S의 단위는 개/Hz이며, 0에 가까울수록 가진 속도의 흔들림에 강건하다. "
  "결과의 우연성을 보기 위해 시드 반복, 실측 적응 녹음 묶음을 바꾸는 3겹 교차검증, 같은 녹음끼리 짝지은 비교를 하였다. 평가에 쓴 6~15번 녹음은 결과를 보고 설정을 다시 맞추는 데 쓰지 않았다(예외는 Ⅴ장 한계 참고).")
